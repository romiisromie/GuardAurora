export function localAssistantReply(text: string): string {
  const q = text.toLowerCase();
  if (q.includes('sos') || q.includes('угроз') || q.includes('преследу') || q.includes('опасн')) {
    return 'Если тебе угрожают, перейди в людное место и позвони в местную экстренную службу. Кнопка SOS только запускает отсчёт и сохраняет событие в журнале: приложение не вызывает службы и не отправляет сообщения контактам.';
  }
  if (q.includes('маршрут') || q.includes('карт')) {
    return 'Карта и список мест в этой версии демонстрационные. Не используй их для навигации или оценки безопасности маршрута.';
  }
  if (q.includes('контакт')) {
    return 'Добавь доверенные контакты на вкладке «Контакты». Автоматической рассылки SOS в этой версии нет.';
  }
  if (q.includes('спокой') || q.includes('паник') || q.includes('страх')) {
    return 'Сделай несколько медленных вдохов и выдохов. Если можешь, позвони или напиши человеку, которому доверяешь.';
  }
  return 'Я локальный помощник GuardAurora. Могу подсказать, как пользоваться SOS и контактами. Ответы формируются на устройстве. В реальной опасности звони в местную экстренную службу.';
}
